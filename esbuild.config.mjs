import esbuild from 'esbuild';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { createBundleNoticePlugin } from './scripts/bundle-notices.mjs';

const root = path.dirname(fileURLToPath(import.meta.url));
const context = await esbuild.context({
  absWorkingDir: root,
  entryPoints: ['src/main.ts'],
  outfile: 'main.js',
  bundle: true,
  write: false,
  metafile: true,
  external: ['obsidian', 'node:fs/promises', 'node:path'],
  format: 'cjs',
  platform: 'browser',
  target: 'es2022',
  sourcemap: 'external',
  logLevel: 'info',
  banner: { js: '/* ObsidianCore Sync — generated by esbuild. Internal plugin ID: vaultsync. */' },
  plugins: [createBundleNoticePlugin({ root, outfile: 'main.js' })],
});
if (process.argv.includes('--watch')) {
  await context.watch();
} else {
  try {
    await context.rebuild();
  } finally {
    await context.dispose();
  }
}
